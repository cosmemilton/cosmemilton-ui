import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const distDir = path.resolve(__dirname, '../dist');
const srcDir = path.resolve(__dirname, '../src');
const expectedDuplicateExports = new Set([
  'CmBox',
  'CmChartFrame',
  'CmCol',
  'CmContainer',
  'CmField',
  'CmForm',
  'CmRow',
  'CmStack',
  'CmText',
  'CmTopbar',
  'CmThemeMenu',
  'CmThemeProvider',
  'CmThemeScript',
  'CmThemeToggle',
  'auroraTheme',
  'blueTheme',
  'cmChartColor',
  'customThemeCSS',
  'darkTheme',
  'defaultTheme',
  'extendThemes',
  'greenTheme',
  'midnightTheme',
  'orangeTheme',
  'redTheme',
  'roseTheme',
  'schoolTheme',
  'themeSelector',
  'themeToCSSBlock',
  'themeToCSSVars',
  'themes',
  'useCmTheme',
  'useOptionalCmTheme',
  'violetTheme',
]);

async function generateManifest() {
  const entries = ['client', 'server', 'theme'];
  const manifest = {};
  
  // 1. Load each entry and extract exported keys
  for (const entry of entries) {
    const entryPath = path.resolve(distDir, `${entry}.js`);
    const module = await import(`file://${entryPath}`);
    
    for (const key of Object.keys(module)) {
      if (key === 'default') continue;
      if (manifest[key] && !expectedDuplicateExports.has(key)) {
        console.warn(`Warning: '${key}' is exported by both '${manifest[key]}' and '${entry}'.`);
      }
      manifest[key] = entry;
    }
  }

  // 2. Write manifest.json
  const manifestPath = path.resolve(distDir, 'manifest.json');
  await fs.writeFile(manifestPath, JSON.stringify(manifest, null, 2), 'utf-8');
  console.log(`✅ Generated dist/manifest.json with ${Object.keys(manifest).length} exports.`);

  // 3. Generate src/index.ts with dummy deprecated exports
  let indexTsContent = `// AUTO-GENERATED FILE - DO NOT EDIT DIRECTLY
// This file is generated by scripts/generate-manifest.mjs
// It provides deprecated dummy exports to guide consumers to the correct entry point.

const throwError = (name: string, entry: string): never => {
  throw new Error(\`O componente "\${name}" deve ser importado de "cosmemilton-ui/\${entry}". Atualize seu import.\`);
};

function createProxy(name: string, entry: string) {
  return new Proxy(function() {}, {
    get() { throwError(name, entry); },
    apply() { throwError(name, entry); },
    construct() { return throwError(name, entry); }
  });
}\n\n`;

  for (const [key, entry] of Object.entries(manifest)) {
    indexTsContent += `/** @deprecated O componente "${key}" foi movido para "cosmemilton-ui/${entry}". */\n`;
    indexTsContent += `export const ${key}: unknown = /*#__PURE__*/ createProxy("${key}", "${entry}");\n`;
  }
  
  indexTsContent += `\n/** @deprecated O entry root "cosmemilton-ui" foi removido. */\n`;
  indexTsContent += `export default new Proxy(function() {}, { get() { throw new Error("cosmemilton-ui v3 não possui entry root. Importe de /client, /server ou /theme."); } });\n`;

  const indexTsPath = path.resolve(srcDir, 'index.ts');
  await fs.writeFile(indexTsPath, indexTsContent, 'utf-8');
  console.log(`✅ Generated src/index.ts with deprecated proxies.`);

  // 4. Generate dist/index.js and dist/index.d.ts to bypass the need for a second tsc run
  let indexJsContent = `// AUTO-GENERATED FILE\n`;
  indexJsContent += `const throwError = (name, entry) => { throw new Error(\`O componente "\${name}" deve ser importado de "cosmemilton-ui/\${entry}". Atualize seu import.\`); };\n`;
  indexJsContent += `function createProxy(name, entry) {\n  return new Proxy(function() {}, {\n    get() { throwError(name, entry); },\n    apply() { throwError(name, entry); },\n    construct() { return throwError(name, entry); }\n  });\n}\n\n`;

  let indexDtsContent = `// AUTO-GENERATED FILE\n`;

  for (const [key, entry] of Object.entries(manifest)) {
    indexJsContent += `export const ${key} = /*#__PURE__*/ createProxy("${key}", "${entry}");\n`;
    indexDtsContent += `/** @deprecated O componente "${key}" foi movido para "cosmemilton-ui/${entry}". */\nexport declare const ${key}: any;\n`;
  }

  indexJsContent += `\nexport default new Proxy(function() {}, { get() { throw new Error("cosmemilton-ui v3 não possui entry root. Importe de /client, /server ou /theme."); } });\n`;
  indexDtsContent += `\n/** @deprecated O entry root "cosmemilton-ui" foi removido. */\ndeclare const _default: any;\nexport default _default;\n`;

  await fs.writeFile(path.resolve(distDir, 'index.js'), indexJsContent, 'utf-8');
  await fs.writeFile(path.resolve(distDir, 'index.d.ts'), indexDtsContent, 'utf-8');
  
  console.log(`✅ Updated dist/index.js and dist/index.d.ts.`);
}

generateManifest().catch(err => {
  console.error('Error generating manifest:', err);
  process.exit(1);
});
